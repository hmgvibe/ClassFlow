    fun text(vararg arguments: Any?): String {
        val resources = applicationContext.value?.resources
        return if (resources != null) resources.getString(resourceId, *arguments)
        else if (arguments.isEmpty()) fallback else String.format(Locale.ROOT, fallback, *arguments)
    }

    companion object {
        private val applicationContext = mutableStateOf<Context?>(null)
        fun initialize(context: Context) {
            // Glance sessions also observe this state and redraw when the language changes.
            applicationContext.value = context.applicationContext.createConfigurationContext(context.resources.configuration)
        }

        /** Keep displayed weekdays and date formats in the same supported language as UI text. */
        fun displayLocale(locale: Locale = applicationContext.value?.resources?.configuration?.locales?.get(0)
            ?: Locale.TRADITIONAL_CHINESE): Locale {
            val simplified = locale.language == "zh" &&
                (locale.script == "Hans" || (locale.script != "Hant" && locale.country in setOf("CN", "SG", "")))
            return if (simplified) Locale.SIMPLIFIED_CHINESE else Locale.TRADITIONAL_CHINESE
        }
    }
